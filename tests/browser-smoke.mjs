  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:4178', { waitUntil: 'networkidle' });
  await page.screenshot({ path: 'tests/guiji-desktop.png', fullPage: true });
  assert.equal(await page.locator('.stat-value').first().textContent(), '42份');

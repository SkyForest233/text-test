  assert.equal(await page.locator('.user-table tbody tr').count(), 1);
  await page.getByRole('button', { name: '查看 gzpenpen 的内容' }).click();
  assert.equal(await page.locator('.detail-file-list>div').count(), 5);
  await page.getByRole('button', { name: '关闭弹窗', exact: true }).click();
  await page.getByRole('button', { name: '清空搜索', exact: true }).click();
  await page.getByRole('checkbox', { name: '选择 gzpenpen', exact: true }).check();
  await page.getByRole('checkbox', { name: '选择 Asternminate', exact: true }).check();

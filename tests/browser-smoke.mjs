  await page.getByRole('button', { name: '确认合并 (2)' }).click();
  await page.locator('.main-nav').getByRole('button', { name: '合并记录' }).click();
  assert.equal(await page.locator('.history-item').count(), 1);
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  assert.equal(await page.locator('.history-item').count(), 0);
  await page.locator('.main-nav').getByRole('button', { name: /待确认内容/ }).click();
  const pendingBefore = await page.locator('.review-item').count();
  await page.getByRole('button', { name: '确认归属', exact: true }).first().click();
  await page.getByText('手动编辑文本', { exact: true }).click();
  await page.getByLabel('这份内容属于谁？').fill('JoelMaud70028, Pap0927, NIUNIU6910');
  await page.getByRole('button', { name: '确认并更新统计' }).click();
  assert.equal(await page.locator('.review-item').count(), pendingBefore - 1);
  await page.getByRole('button', { name: '导出结果', exact: true }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出 CSV' }).click();
  const downloaded = await download;
  console.log('Download filename:', downloaded.suggestedFilename());
  assert.ok(downloaded.suggestedFilename().endsWith('.csv'));
  const csv = await readFile(await downloaded.path(), 'utf8');
  assert.ok(csv.includes('用户名') && csv.includes('gzpenpen'));
  await page.locator('.main-nav').getByRole('button', { name: '分析概览', exact: true }).click();
  await page.getByRole('button', { name: /已经复制了文件名/ }).click();
  await page.getByRole('textbox', { name: '文件名清单', exact: true }).fill('Alice_2089930283558801756_1___.mp4\nAlice_2089930283558801757_1___.mp4\nunknown-name');
  await page.getByRole('button', { name: '开始分析' }).click();
  assert.equal(await page.locator('.stat-value').first().textContent(), '3份');
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('.stat-value').first().textContent(), '3份');
  await page.getByRole('button', { name: '试试示例' }).click();
  await page.locator('input[type=file]').setInputFiles({ name: 'test.txt', mimeType: 'text/plain', buffer: Buffer.from('Tester_2089930283558801756_1___.mp4\nTester_2089930283558801756_2___.mp4') });
  await page.waitForFunction(() => document.querySelector('.stat-value')?.textContent === '2份');
  await page.locator('.main-nav').getByRole('button', { name: '解析设置' }).click();
  await page.getByRole('switch', { name: '按作品 ID 去重' }).click();
  await page.locator('.main-nav').getByRole('button', { name: '用户列表' }).click();
  assert.equal(await page.locator('.amount-cell strong').first().innerText(), '1');
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
